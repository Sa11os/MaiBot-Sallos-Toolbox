"""将分文件源码打包为 MaiBot 支持的单文件页面。"""

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from sallos_toolbox.features.appearance.models import REGION_PROPERTIES, AppearanceTheme  # noqa: E402
from sallos_toolbox.features.appearance.presets import builtin_presets  # noqa: E402


def build(check: bool = False) -> None:
    source = ROOT / "web/src"
    generated = source / "generated/theme-data.js"
    data = {
        "DEFAULT_THEME": AppearanceTheme().model_dump(),
        "THEME_SCHEMA": AppearanceTheme.model_json_schema(),
        "BUILTIN_PRESETS": builtin_presets(),
        "REGION_PROPERTIES": sorted(REGION_PROPERTIES),
    }
    data_js = (
        "// Generated by scripts/build_webui.py.\n"
        + "\n".join(f"export const {key} = {json.dumps(value, ensure_ascii=False)};" for key, value in data.items())
        + "\n"
    )
    scripts = [data_js]
    for name in [
        "shared/theme-contract.js",
        "shared/bridge.js",
        "shared/confirm.js",
        "features/appearance/preview.js",
        "features/appearance/editor.js",
        "features/appearance/presets.js",
        "main.js",
    ]:
        scripts.append((source / name).read_text(encoding="utf-8"))
    bundled = "\n".join(re.sub(r"^import .*?;\n", "", script, flags=re.M) for script in scripts)
    bundled = re.sub(r"^export ", "", bundled, flags=re.M).replace("</script", "<\\/script")
    css = "\n".join((source / name).read_text(encoding="utf-8") for name in ["styles/base.css", "styles/editor.css"])
    html = (source / "index.html").read_text(encoding="utf-8")
    html = html.replace("<!-- STYLES -->", f"<style>\n{css}\n</style>")
    html = html.replace("<!-- SCRIPTS -->", f'<script type="module">\n{bundled}\n</script>')

    def parameter(rule: dict) -> dict:
        if "$ref" in rule:
            rule = data["THEME_SCHEMA"]["$defs"][rule["$ref"].split("/")[-1]]
        result = {"type": rule["type"], "required": True}
        for original, target in [("maxLength", "max_length"), ("minimum", "minimum"), ("maximum", "maximum")]:
            if original in rule:
                result[target] = rule[original]
        if "enum" in rule:
            result["choices"] = rule["enum"]
        if rule["type"] == "object":
            result["properties"] = {key: parameter(item) for key, item in rule["properties"].items()}
        return result

    revision = {"type": "integer", "required": True, "minimum": 0}
    identifier = {"type": "string", "required": True, "max_length": 32}
    declaration = {
        "schema_version": 2,
        "required_capabilities": ["custom_pages", "structured_arguments"],
        "workspace_title": "Sallos 工具箱",
        "pages": [
            {
                "id": "appearance",
                "title": "外观",
                "placement": "workspace",
                "icon": "settings",
                "mode": "custom",
                "entry": "web/appearance.html",
                "layout": "document",
                "queries": {"catalog": {"api": "appearance_catalog"}},
                "actions": {
                    "apply": {
                        "api": "appearance_apply",
                        "parameters": {"theme": parameter(data["THEME_SCHEMA"])},
                        "confirmation": "将这套外观应用到此服务器的所有 Dashboard 浏览器？",
                    },
                    "preview": {
                        "api": "appearance_preview",
                        "parameters": {"theme": parameter(data["THEME_SCHEMA"])},
                        "confirmation": "所有 Dashboard 浏览器将预览此风格 20 秒，随后自动恢复。继续？",
                    },
                    "reset": {"api": "appearance_reset", "confirmation": "恢复此服务器的原有 Dashboard 外观？"},
                    "save": {
                        "api": "appearance_save",
                        "parameters": {
                            "theme": parameter(data["THEME_SCHEMA"]),
                            "preset_id": identifier,
                            "revision": revision,
                        },
                    },
                    "delete": {
                        "api": "appearance_delete",
                        "parameters": {
                            "preset_id": identifier,
                            "revision": revision,
                        },
                        "confirmation": "删除这个个人外观预设？",
                    },
                },
            }
        ],
    }
    outputs = {
        generated: data_js,
        ROOT / "web/appearance.html": html,
        ROOT / "webui.json": json.dumps(declaration, ensure_ascii=False, indent=2) + "\n",
    }
    runtime_sources = [
        data_js,
        (source / "shared/theme-contract.js").read_text(encoding="utf-8"),
        (source / "features/appearance/runtime.js").read_text(encoding="utf-8"),
    ]
    runtime = "\n".join(re.sub(r"^import .*?;\n", "", script, flags=re.M) for script in runtime_sources)
    runtime = re.sub(r"^export ", "", runtime, flags=re.M)
    outputs[ROOT / "sallos_toolbox/features/appearance/integration/runtime.js"] = "(() => {\n" + runtime + "\n})();\n"
    for path, content in outputs.items():
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                raise SystemExit(f"构建产物需要更新：{path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
    print("WebUI artifacts verified" if check else "WebUI built")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    build(parser.parse_args().check)
